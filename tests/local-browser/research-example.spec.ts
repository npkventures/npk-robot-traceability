import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

for (const width of [390, 1440]) {
  test(`public research reconstruction loads and compares at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/workspace/?example=flowsteps');
    await page.getByRole('button', { name: 'Load synthetic example', exact: true }).click();
    await expect(page.getByRole('status')).toContainText('all displayed dates are invented');
    await page.getByRole('combobox', { name: 'Test to check', exact: true }).selectOption('flowsteps-3968-failure');
    await page.getByRole('combobox', { name: 'Compare with a successful test', exact: true }).selectOption('flowsteps-3969-success');
    const steps = page.getByRole('row').filter({ hasText: 'Euler integration steps' });
    await expect(steps).toContainText('10 1');
    await expect(steps).toContainText('1 1');
    await expect(steps).toContainText('Changed');
    await expect(page.getByRole('row').filter({ hasText: 'Demo timeline status' })).toContainText('All displayed dates are invented ordering placeholders.');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
    expect(errors).toEqual([]);
    await page.screenshot({ path: `test-results/flowsteps-${width}.png`, fullPage: true });
  });
}

test('real-source feedback, unresolved investigation, exports and reimport agree with published outcomes', async ({ page }) => {
  const uploads: string[] = [];
  page.on('request', request => { if (request.method() !== 'GET' && !request.url().includes('__nextjs')) uploads.push(request.url()); });
  await page.goto('/workspace/?example=flowsteps');
  await page.getByRole('button', { name: 'Load synthetic example', exact: true }).click();
  await page.getByRole('combobox', { name: 'Test to check', exact: true }).selectOption('flowsteps-3968-failure');
  await page.getByRole('combobox', { name: 'Compare with a successful test', exact: true }).selectOption('flowsteps-3969-success');
  await page.getByText('Investigate this test', {exact:true}).click();
  const panel = page.getByRole('region', { name: 'Investigation', exact: true });
  await expect(panel).toContainText('No sufficiently comparable successful baseline found');
  const summary = panel.getByRole('region', { name: 'Investigation summary', exact: true });
  await expect(summary).toContainText('1 recorded configuration or condition difference is');
  await expect(summary).toContainText('2 measurement differences');
  await expect(summary).toContainText('9 unknown comparisons');
  const handoffDownload = page.waitForEvent('download');
  await summary.getByRole('button', { name: 'Download investigation handoff' }).click();
  const handoff = await readFile((await (await handoffDownload).path())!, 'utf8');
  expect(handoff).toContain('flowsteps-episode-3968 revision 1');
  expect(handoff).toContain('Recorded differences do not prove causation');
  expect(handoff).toContain('synthetic placeholders');
  const form = panel.getByRole('form', { name: 'Record investigation' });
  await form.getByLabel('Investigation author').fill('Automated test - not a researcher conclusion');
  await form.getByLabel('Investigation note', { exact: true }).fill('Source outcome is failure; Euler steps changed from 10 to 1. Individual failure cause remains unknown.');
  await form.getByLabel('Investigation state').selectOption('confirmed-by-engineer');
  await form.getByRole('button', { name: 'Append investigation entry' }).click();
  await expect(form.getByRole('alert')).toContainText('confirmation requires');
  await form.getByLabel('Investigation state').selectOption('unresolved');
  await form.getByRole('button', { name: 'Append investigation entry' }).click();
  const reportDownload = page.waitForEvent('download');
  await panel.getByRole('button', { name: 'Export investigation report' }).click();
  const report = JSON.parse(await readFile((await (await reportDownload).path())!, 'utf8'));
  expect(report.investigation.state).toBe('unresolved');
  expect(report.evidence.map((e: { run: { outcome: string } }) => e.run.outcome)).toEqual(['success', 'failure']);
  expect(report.analysis.counts.unknown).toBe(9);
  expect(report.retests).toEqual([]);
  const review = page.getByRole('region', { name: 'Failure review', exact: true });
  await review.getByRole('button', { name: 'Review all failed tests' }).click();
  const reviewDownload = page.waitForEvent('download');
  await review.getByRole('button', { name: 'Download review packet', exact: true }).click();
  const packet = JSON.parse(await readFile((await (await reviewDownload).path())!, 'utf8'));
  expect(packet.counts.failures).toBe(1);
  expect(packet.counts.withoutBaseline).toBe(1);
  expect(packet.failures[0].status).toBe('needs_follow_up');
  const bundleDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  const raw = await readFile((await (await bundleDownload).path())!, 'utf8');
  await page.reload();
  await page.getByLabel('Import JSON').setInputFiles({ name: 'flowsteps-validation.json', mimeType: 'application/json', buffer: Buffer.from(raw) });
  await page.getByRole('combobox', { name: 'Test to check', exact: true }).selectOption('flowsteps-3968-failure');
  await panel.getByLabel('Investigation history').selectOption(report.investigation.id);
  await expect(panel).toContainText('Individual failure cause remains unknown.');
  const restoredDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  expect(JSON.parse(await readFile((await (await restoredDownload).path())!, 'utf8'))).toEqual(JSON.parse(raw));
  expect(uploads).toEqual([]);
});
