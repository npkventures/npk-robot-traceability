import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

for (const width of [320, 1440]) test(`connected homepage components at ${width}px`, async ({ page }) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  await expect(page.locator('.t-build-faster .t-typewriter-text')).toHaveText('Build faster');
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  const menu = nav.getByRole('button', { name: 'Menu', exact: true });
  await menu.click();
  await expect(nav.getByRole('link', { name: 'Services', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(menu).toBeFocused();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(nav.getByRole('link', { name: 'Services', exact: true })).not.toBeVisible();
  await expect(page.locator('.t-build-faster .t-typewriter-text')).toHaveText('Build faster');
  await expect.poll(()=>page.locator('.t-build-faster .t-typewriter-text').textContent()).not.toBe('Build faster');
  await expect(page.locator('.t-build-faster .t-typewriter-text')).toHaveText('Build faster');
  await expect(page.locator('.t-investigation-input, #investigation-question')).toHaveCount(0);
  await expect(page.getByRole('button', {name:/logo loop/i})).toHaveCount(0);
  expect(await page.locator('main .t-hero, main > section').evaluateAll(nodes=>nodes.map(n=>n.classList[0]))).toEqual(['t-hero','t-workflow','t-product','t-onboarding','t-invitation']);
  await page.locator('.t-investigation-prompt').scrollIntoViewIfNeeded();
  await expect(page.locator('.t-investigation-prompt .t-typewriter-text')).toHaveText('Where did this run go wrong?');
  await page.locator('.t-developer-tools').scrollIntoViewIfNeeded();
  await expect(page.locator('.logoloop')).toBeVisible();
  await expect(page.locator('.t-developer-tools')).toContainText('GitHub');
  await page.locator('.logoloop').hover();
  const track = page.locator('.logoloop__track');
  const position = await track.evaluate(node => node.style.transform);
  await expect.poll(() => track.evaluate(node => node.style.transform)).not.toBe(position);
  await page.locator('.t-workflow').scrollIntoViewIfNeeded();
  const wheel = page.locator('.t-wheel');
  await wheel.focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.t-offering-detail h3')).toHaveText('Run comparison');
  await page.keyboard.press('End');
  await expect(page.locator('.t-offering-detail h3')).toHaveText('Investigation handoffs');
  await page.getByRole('button', { name: 'Next capability', exact: true }).click();
  await expect(page.locator('.t-offering-detail h3')).toHaveText('Configuration history');
  for (const href of ['/walkthrough/#developer-tools', '/walkthrough/#team-review', '/services/run-comparison/']) expect((await page.request.get(href)).status()).toBe(200);
  await expect(page.locator('.t-pricing-placeholder, .pixel-card, a[href="/#pricing"]')).toHaveCount(0);
  await expect(page.locator('.t-invitation')).toContainText('Pricing is tailored to your team after a demo and discussion.');
  await expect(page.locator('.t-invitation').getByRole('link', { name: 'Get started' })).toHaveAttribute('href', '/login/?mode=signup');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(page.locator('.logoloop')).toHaveCount(0);
  await expect(page.locator('.t-tools-static a')).toHaveCount(3);
  await expect(page.locator('.t-typewriter-cursor')).toHaveCount(0);
  await page.getByRole('button', { name: 'Next capability', exact: true }).click();
  await expect(page.locator('.t-offering-detail h3')).toHaveText('Run comparison');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({ path: `test-results/home-components-${width}.png`, fullPage: true });
  expect(errors).toEqual([]);
});

test('homepage remains complete without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, baseURL });
  const page = await context.newPage();
  await page.goto('/');
  await expect(page.locator('.t-build-faster .t-typewriter-text')).toHaveText('Build faster');
  await expect(page.locator('.t-offerings-fallback article')).toHaveCount(6);
  await expect(page.locator('.t-tools-static a')).toHaveCount(3);
  await expect(page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Services', exact: true })).toBeVisible();
  await expect(page.locator('main .t-hero, main > section')).toHaveCount(5);
  await context.close();
});
